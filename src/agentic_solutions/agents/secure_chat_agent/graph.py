"""Agent 3: the chat loop from agent 2 plus a prompt-injection guard.

What's new compared with agent 2 (chat_agent)
---------------------------------------------
* Two extra nodes: `guard` screens every prompt BEFORE Claude sees it, and
  `refuse` replies when a threat is found.
* A second conditional edge (after `guard`), so the graph now has two routers.
* Startup work: the `ThreatGuard` embeds the threat library once, when the
  graph is built, not on every question.
* State beyond `messages`: `threat` and `refusal` carry the guard's verdict
  from one node to the next.
* `RemoveMessage`: how a node deletes something from the conversation.

The graph
---------

            +-------------------------------------------------+
            v                                                 |
    START -> ask --(route_after_ask)--> guard --(route_after_guard)--> answer --+
              ^   \\                       |                                     |
              |    +--"stop"--> END       +--threat--> refuse ---+              |
              |                                                  |              |
              +--(empty input)                                   v              |
              ^------------------------------------------------- ask <----------+

In words: ask -> guard -> (answer | refuse) -> ask ... until "stop".
"""
from typing import Annotated, Literal, TypedDict

from langchain_core.messages import RemoveMessage, SystemMessage
from langgraph.graph import END, START, StateGraph
from langgraph.graph.message import add_messages

from agentic_solutions.agents.chat_agent.graph import STOP_WORD, ask
from agentic_solutions.agents.secure_chat_agent.guard import ThreatGuard
from agentic_solutions.common.llm import get_llm

SYSTEM_PROMPT = "You are a helpful assistant. Answer concisely and accurately."

# Fixed text, not generated by the LLM: a refusal must never depend on the
# very model an attacker is trying to manipulate.
REFUSAL_MESSAGE = (
    "I'm sorry, but I can't help with that request. It looks like an attempt "
    "to override my instructions or access something I'm not able to share, "
    "so I won't act on it. I'm happy to help with any other question."
)


class State(TypedDict):
    """Data flowing through the graph.

    `messages` has the `add_messages` reducer (append, see agent 2).
    `threat` and `refusal` have no reducer, so each update simply replaces the
    old value, which is what we want for "the verdict on the latest prompt".
    """

    messages: Annotated[list, add_messages]
    threat: str | None  # e.g. "prompt_extraction (0.91)", None if the prompt is clean
    refusal: str | None  # the refusal text to show the user, None if not refused


def build_graph(guard: ThreatGuard | None = None):
    """Build and compile the graph.

    This is where the startup work happens: with no `guard` given, creating a
    `ThreatGuard` loads the embedding model and embeds the threat library.
    Tests pass in a guard built with a fake model so they stay fast and offline.
    """
    guard = guard or ThreatGuard()

    # ---- Nodes ----------------------------------------------------------
    # The nodes are defined inside build_graph so they can use `guard`
    # (a closure) without storing it in the State.

    def guard_prompt(state: State) -> dict:
        """Node: check the newest user message against the threat library."""
        match = guard.check(state["messages"][-1].content)
        threat = f"{match.category} ({match.score:.2f})" if match else None
        return {"threat": threat}

    def refuse(state: State) -> dict:
        """Node: reply with a polite refusal and quarantine the bad prompt.

        The offending message is REMOVED from the conversation. Otherwise it
        would sit in the history and be sent to Claude with every later
        question, giving the attack a second chance to work.
        """
        bad_message = state["messages"][-1]
        return {
            "messages": [RemoveMessage(id=bad_message.id)],
            "refusal": REFUSAL_MESSAGE,
        }

    def answer(state: State) -> dict:
        """Node: ask Claude (same as agent 2). Only clean prompts get here."""
        llm = get_llm()
        reply = llm.invoke([SystemMessage(SYSTEM_PROMPT), *state["messages"]])
        return {"messages": [reply], "refusal": None}

    # ---- Routers --------------------------------------------------------
    def route_after_ask(state: State) -> Literal["guard", "ask", "__end__"]:
        """stop -> END, empty -> ask again, otherwise -> guard."""
        text = state["messages"][-1].content.strip().lower()
        if text == STOP_WORD:
            return END
        if not text:
            return "ask"
        return "guard"

    def route_after_guard(state: State) -> Literal["refuse", "answer"]:
        """Threat found -> refuse, otherwise -> answer."""
        return "refuse" if state["threat"] else "answer"

    # ---- Wiring ---------------------------------------------------------
    builder = StateGraph(State)
    builder.add_node("ask", ask)  # reused from agent 2
    builder.add_node("guard", guard_prompt)
    builder.add_node("refuse", refuse)
    builder.add_node("answer", answer)

    builder.add_edge(START, "ask")
    builder.add_conditional_edges("ask", route_after_ask)
    builder.add_conditional_edges("guard", route_after_guard)
    builder.add_edge("refuse", "ask")
    builder.add_edge("answer", "ask")

    return builder.compile()
